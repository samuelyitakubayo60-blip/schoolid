CREATE TABLE IF NOT EXISTS schools (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(190) NOT NULL, slug VARCHAR(120) UNIQUE NOT NULL,
 school_code VARCHAR(60), email VARCHAR(190), phone VARCHAR(40), address VARCHAR(255), logo_url TEXT,
 status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK(status IN ('pending','active','suspended','rejected')),
 subscription_plan VARCHAR(20) NOT NULL DEFAULT 'none', subscription_status VARCHAR(20) NOT NULL DEFAULT 'none',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, full_name VARCHAR(190) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK(status IN ('active','disabled')),
 is_platform_owner BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS memberships (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 role_key VARCHAR(30) NOT NULL CHECK(role_key IN ('director','dos','patron','matron')),
 status VARCHAR(20) NOT NULL DEFAULT 'active', UNIQUE(school_id,user_id)
);
CREATE TABLE IF NOT EXISTS academic_years (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
 name VARCHAR(80) NOT NULL, is_current BOOLEAN NOT NULL DEFAULT FALSE, UNIQUE(school_id,name)
);
CREATE TABLE IF NOT EXISTS classes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
 academic_year_id BIGINT REFERENCES academic_years(id) ON DELETE SET NULL,
 name VARCHAR(100) NOT NULL, stream VARCHAR(80) NOT NULL DEFAULT '', UNIQUE(school_id,name,stream)
);
CREATE TABLE IF NOT EXISTS class_assignments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
 class_id BIGINT NOT NULL REFERENCES classes(id) ON DELETE CASCADE, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 UNIQUE(class_id,user_id)
);
CREATE TABLE IF NOT EXISTS students (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
 class_id BIGINT REFERENCES classes(id) ON DELETE SET NULL, admission_number VARCHAR(100) NOT NULL,
 first_name VARCHAR(100) NOT NULL, last_name VARCHAR(100) NOT NULL,
 gender VARCHAR(20) NOT NULL DEFAULT 'not_stated' CHECK(gender IN ('female','male','other','not_stated')),
 date_of_birth DATE, photo_url TEXT, status VARCHAR(20) NOT NULL DEFAULT 'active',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(school_id,admission_number)
);
CREATE TABLE IF NOT EXISTS id_cards (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
 student_id BIGINT NOT NULL UNIQUE REFERENCES students(id) ON DELETE CASCADE,
 qr_token CHAR(64) NOT NULL UNIQUE, status VARCHAR(20) NOT NULL DEFAULT 'active', issued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id BIGINT, user_id BIGINT,
 action VARCHAR(120) NOT NULL, details_json JSONB, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS school_settings (
 school_id BIGINT PRIMARY KEY REFERENCES schools(id) ON DELETE CASCADE, academic_label VARCHAR(100) DEFAULT 'Academic Year',
 card_color VARCHAR(20) DEFAULT '#123f72'
);
CREATE INDEX IF NOT EXISTS idx_students_school_class ON students(school_id,class_id);
CREATE INDEX IF NOT EXISTS idx_memberships_user ON memberships(user_id,school_id);
